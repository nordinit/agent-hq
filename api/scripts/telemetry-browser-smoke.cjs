/** Headless acceptance checks for the disposable telemetry UI/API fixture only. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const {chromium} = require('playwright-core');

async function main() {
  const base = process.env.TELEMETRY_SMOKE_UI_URL || 'http://127.0.0.1:3568';
  if (!/^http:\/\/127\.0\.0\.1:3568$/.test(base)) throw new Error('Use only the isolated telemetry smoke UI on port3568.');
  const browser = await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:1100}});
  page.setDefaultTimeout(15000);
  const failures = [], results = [], requests = [];
  page.on('pageerror', error => failures.push(error.message));
  page.on('request', request => {if(request.url().includes('/telemetry/v2'))requests.push({method:request.method(),url:request.url()});});
  const responseFor = (path, method='POST') => page.waitForResponse(response => response.url().includes('/api/v1/telemetry/v2/') && new URL(response.url()).pathname.endsWith(path) && response.request().method()===method);
  async function action(button, path, check, status=200, method='POST') {
    const target=typeof button==='string'?page.getByRole('button',{name:button,exact:true}):button;
    const [response]=await Promise.all([responseFor(path,method),target.click()]);
    const body=await response.json();
    assert.equal(response.status(),status,JSON.stringify(body));
    if(check)check(body);
    return body;
  }
  const select = (name,value) => page.locator('label').filter({has:page.locator('span').filter({hasText:new RegExp('^'+name.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')+'$')})}).locator('select').selectOption(value);
  const suffix=Date.now().toString();
  try {
    await page.goto(base+'/telemetry?project_id=11');
    await page.getByRole('heading',{name:'Metric definition',exact:true}).waitFor();
    await select('Measurement','numeric');
    await page.getByLabel('Metric name',{exact:true}).fill('Browser amount '+suffix);
    await page.getByLabel('Stable family key').fill('browser_amount_'+suffix);
    await select('Canonical numeric field',{label:'Proposal amount'});
    await action('Preview calculation','/queries/preview',body=>{assert.equal(body.value,210);assert.equal(body.sample_count,6);});
    const proof=responseFor('/contributors','GET');
    await page.getByRole('button',{name:'Contributing records',exact:true}).click();
    const contributors=await (await proof).json();
    assert.equal(contributors.total,6);assert.equal(contributors.contributors.reduce((sum,row)=>sum+Number(row.value),0),210);
    await page.getByRole('link',{name:'Task #1001',exact:true}).waitFor();
    results.push('Guided canonical numeric sum210; six retained contributors agree.');
    const metric=await action('Save metric','/metrics',body=>assert.equal(body.revision,1),201);
    await page.getByRole('button',{name:'Reports',exact:true}).click();
    await page.getByRole('button',{name:'New report',exact:true}).click();
    await page.getByLabel('Report name',{exact:true}).fill('Browser report '+suffix);
    await page.getByLabel('Stable key',{exact:true}).fill('browser_report_'+suffix);
    await page.getByRole('checkbox',{name:new RegExp('Browser amount '+suffix)}).check();
    const report=await action('Save report','/reports',undefined,201);
    const reportCard=page.locator('div.rounded-xl').filter({has:page.getByRole('heading',{name:new RegExp('^Browser report '+suffix+' ')})});
    await action(reportCard.getByRole('button',{name:'Open report',exact:true}),'/queries',body=>assert.equal(body.results[0].value,210));
    await action(reportCard.getByRole('button',{name:'Freeze displayed result',exact:true}),'/snapshots',body=>assert.equal(body.snapshot,true),201);
    results.push('Metric/report save, pinned report execution, and frozen snapshot.');
    await page.getByRole('button',{name:'Metric library',exact:true}).click();
    await page.locator('div.rounded-xl').filter({has:page.getByRole('heading',{name:new RegExp('^Browser amount '+suffix+' ')})}).getByRole('button',{name:'Edit definition',exact:true}).click();
    await select('Calculation','mean');
    await action('Save new revision','/revisions',body=>assert.equal(body.revision,2),201);
    await page.getByRole('button',{name:'Reports',exact:true}).click();
    await action(reportCard.getByRole('button',{name:'Open report',exact:true}),'/queries',body=>assert.equal(body.results[0].value,210));
    results.push('Editing metric to mean preserves the report’s original sum revision.');
    await page.getByRole('button',{name:'Scoped meanings',exact:true}).click();
    await page.getByLabel('Metric family key',{exact:true}).fill('browser_amount_'+suffix);
    await select('Pinned metric revision',{label:'Browser amount '+suffix+' · revision 2'});
    await page.getByRole('heading',{name:'After this save',exact:true}).waitFor();
    await action('Save binding','/bindings',body=>assert.equal(body.binding.disabled,false),200,'PUT');
    await action('Run effective metric for this scope','/queries',body=>assert.equal(body.results[0].value,35));
    await select('Workflow','111');
    await page.getByLabel('Metric family key',{exact:true}).fill('browser_amount_'+suffix);
    await page.getByText('Inherited',{exact:true}).waitFor();
    await page.getByRole('checkbox',{name:'Disable this family at this scope',exact:true}).check();
    await page.getByRole('heading',{name:'After this save',exact:true}).waitFor();
    await action('Save binding','/bindings',body=>assert.equal(body.binding.disabled,true),200,'PUT');
    await action('Run effective metric for this scope','/queries',body=>{assert.equal(body.disabled,6);assert.deepEqual(body.results,[]);});
    results.push('Scoped binding preview/save, inherited project mean35, and workflow disable suppresses six tasks.');
    await page.getByRole('heading',{name:'Binding resolution preview',exact:true}).scrollIntoViewIfNeeded();
    await page.screenshot({path:'/private/tmp/telemetry-browser-bindings.png',fullPage:true});
    await select('Workflow','');
    await select('Workflow type','');
    await page.getByRole('button',{name:'New metric',exact:true}).click();
    await select('Measurement','first_pass');
    await select('Journey / interval starts when','event:task.created');
    await select('Success / interval ends when','status:approved');
    await select('Rework disqualifies first pass when','outcome:changes_requested');
    await select('Final unsuccessful result','status:rejected');
    await select('Cancellation','status:cancelled');
    await action('Preview calculation','/queries/preview',body=>{assert.equal(body.numerator,2);assert.equal(body.denominator,4);assert.equal(body.value,.5);});
    await select('Denominator','successful');
    await action('Preview calculation','/queries/preview',body=>{assert.equal(body.numerator,2);assert.equal(body.denominator,3);});
    await page.screenshot({path:'/private/tmp/telemetry-browser-smoke.png',fullPage:true});
    await page.getByRole('heading',{name:'Results',exact:true}).scrollIntoViewIfNeeded();
    await page.screenshot({path:'/private/tmp/telemetry-browser-results.png',fullPage:true});
    results.push('Configured first pass2/4; successful-only denominator2/3.');
    await page.getByRole('button',{name:'Advanced JSON',exact:true}).click();
    await page.getByLabel('Versioned definition').fill('{ invalid');
    await page.getByRole('button',{name:'Preview calculation',exact:true}).click();
    await page.getByRole('alert').filter({hasText:"Expected property name"}).waitFor();
    results.push('Invalid draft is shown as an error.');
    await page.getByRole('button',{name:'New metric',exact:true}).click();
    await select('Project','');
    await select('Project','12');
    await page.getByRole('heading',{name:'Metric definition',exact:true}).waitFor();
    await select('Measurement','milestone');
    await select('Measured milestone','status:submitted');
    await action('Preview calculation','/queries/preview',body=>{assert.equal(body.value,1);assert.equal(body.scope.project_id,12);});
    results.push('Project filter and independently configured submission milestone return1.');
    assert.deepEqual(failures,[]);
    const output={checked_at:new Date().toISOString(),ui_url:base,fixture:'disposable synthetic PostgreSQL',results,metric_id:metric.id,report_id:report.id,page_errors:failures};
    fs.writeFileSync('/private/tmp/telemetry-browser-smoke-results.json',JSON.stringify(output,null,2)+'\n');
    console.log(JSON.stringify(output));
  } catch(error) {
    console.error(JSON.stringify({completed:results,requests,page_errors:failures,visible_text:await page.locator('body').innerText()}));
    await page.screenshot({path:'/private/tmp/telemetry-browser-smoke-failure.png',fullPage:true});
    throw error;
  } finally { await browser.close(); }
}
main().catch(error=>{console.error(error);process.exitCode=1;});
