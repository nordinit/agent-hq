-- The tool definitions each MCP server advertised (tools/list) when a run launched, so the
-- context view can show which tools an agent's model was given and how much prompt space their
-- definitions take. Definitions are stored once per distinct server configuration and tool list;
-- each run links to the snapshot it used.
CREATE TABLE IF NOT EXISTS agents.mcp_tool_snapshots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL REFERENCES core.tenants(id) ON DELETE CASCADE,
    mcp_server_id bigint REFERENCES agents.mcp_servers(id) ON DELETE CASCADE,
    server_name text NOT NULL,
    -- sha256 of the materialized launch config (command, args, cwd, env names and value digests).
    config_fingerprint text NOT NULL,
    -- sha256 of the advertised definitions, so a server upgrade under the same config is a new row.
    definitions_fingerprint text NOT NULL,
    tools jsonb NOT NULL,
    tool_count integer NOT NULL,
    definition_chars integer NOT NULL,
    first_seen_at timestamptz NOT NULL DEFAULT now(),
    last_seen_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, config_fingerprint, definitions_fingerprint)
);

CREATE INDEX IF NOT EXISTS mcp_tool_snapshots_config_idx
    ON agents.mcp_tool_snapshots (tenant_id, config_fingerprint, last_seen_at DESC);
CREATE INDEX IF NOT EXISTS mcp_tool_snapshots_server_idx
    ON agents.mcp_tool_snapshots (tenant_id, mcp_server_id, last_seen_at DESC);

CREATE TABLE IF NOT EXISTS runs.run_mcp_tool_snapshots (
    tenant_id bigint NOT NULL REFERENCES core.tenants(id) ON DELETE CASCADE,
    instance_id bigint NOT NULL REFERENCES runs.job_instances(id) ON DELETE CASCADE,
    server_name text NOT NULL,
    snapshot_id bigint NOT NULL REFERENCES agents.mcp_tool_snapshots(id) ON DELETE CASCADE,
    recorded_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (instance_id, server_name)
);

CREATE INDEX IF NOT EXISTS run_mcp_tool_snapshots_snapshot_idx
    ON runs.run_mcp_tool_snapshots (snapshot_id);

-- The Context page lists an agent's recorded runs newest first.
CREATE INDEX IF NOT EXISTS idx_dispatch_context_bundles_agent
    ON runs.dispatch_context_bundles (tenant_id, agent_id, id DESC);
