-- Store supplemental skill-package files in tenant-owned database records so the UI and
-- runtimes do not need to expose or depend on host-specific fs_path values.
--
-- The SQLite source also contained two skills whose TEXT-affinity content values were written
-- as BLOBs. The PostgreSQL COPY migration encoded every Buffer as a bytea literal, but the
-- destination column is text, leaving values such as "\x2d2d2d..." visible in the editor.
-- Decode every complete, even-length hex value in skills.content back to UTF-8. convert_from
-- deliberately fails the migration instead of silently replacing invalid UTF-8.

BEGIN;

DO $migration$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conrelid = 'skills'::regclass
      AND conname = 'uq_skills_tenant_id_id'
  ) THEN
    ALTER TABLE skills
      ADD CONSTRAINT uq_skills_tenant_id_id UNIQUE (tenant_id, id);
  END IF;
END
$migration$;

CREATE TABLE IF NOT EXISTS skill_files (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  tenant_id bigint NOT NULL,
  skill_id bigint NOT NULL,
  path text NOT NULL,
  content text NOT NULL DEFAULT '',
  created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS'),
  updated_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS'),
  PRIMARY KEY (id),
  CONSTRAINT uq_skill_files_tenant_skill_path UNIQUE (tenant_id, skill_id, path),
  CONSTRAINT ck_skill_files_safe_path CHECK (
    path <> ''
    AND path <> 'SKILL.md'
    AND path !~ '^/'
    AND path !~ '(^|/)\.\.?(/|$)'
    AND path !~ E'\\\\'
    AND path !~ '//'
  ),
  CONSTRAINT fk_skill_files_skill FOREIGN KEY (tenant_id, skill_id)
    REFERENCES skills (tenant_id, id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_skill_files_tenant_skill ON skill_files (tenant_id, skill_id);

UPDATE skills
SET content = convert_from(decode(substr(content, 3), 'hex'), 'UTF8'),
    updated_at = to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
WHERE content ~ '^\\x(?:[0-9A-Fa-f]{2})+$';

COMMIT;
